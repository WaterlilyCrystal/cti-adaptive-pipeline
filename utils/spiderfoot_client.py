import os
import requests
import logging
import time
import json
from dotenv import load_dotenv

load_dotenv()

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

class SpiderFootClient:
    def __init__(self):
        self.base_url = os.getenv("SPIDERFOOT_SERVER_URL", "http://127.0.0.1:5001").rstrip('/')
        self.api_key = os.getenv("SPIDERFOOT_API_KEY", "")
        
    def start_scan(self, scan_name: str, target: str, module_list: list = None) -> str:
        """Starts a new SpiderFoot scan against a specific target."""
        endpoint = f"{self.base_url}/api/startscan"
        if not module_list:
            module_list = ["sfp_abuseipdb", "sfp_virustotal", "sfp_shodan", "sfp_whois"]
            
        payload = {
            "scanname": scan_name,
            "scantarget": target,
            "modulelist": ",".join(module_list),
            "key": self.api_key
        }
        
        try:
            response = requests.post(endpoint, data=payload, timeout=15)
            if response.status_code == 200:
                result = response.json()
                if result[0] == "SUCCESS":
                    return result[1] # Returns scan_id
        except Exception as e:
            logging.error(f"Failed to connect to SpiderFoot server: {str(e)}")
        return ""

    def get_scan_status(self, scan_id: str) -> str:
        """Checks the status of an ongoing scan (RUNNING, FINISHED, etc.)."""
        endpoint = f"{self.base_url}/api/scanstatus"
        params = {"id": scan_id, "key": self.api_key}
        try:
            response = requests.get(endpoint, params=params, timeout=10)
            if response.status_code == 200:
                return response.json()[1]
        except Exception as e:
            logging.error(f"Error checking scan status: {str(e)}")
        return "UNKNOWN"

    def get_scan_results(self, scan_id: str) -> list:
        """Fetches the structural OSINT data generated by the completed scan."""
        endpoint = f"{self.base_url}/api/scanresults"
        params = {"id": scan_id, "key": self.api_key}
        try:
            response = requests.get(endpoint, params=params, timeout=15)
            if response.status_code == 200:
                return response.json()
        except Exception:
            pass
        return []

