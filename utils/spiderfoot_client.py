def quick_osint_scan(target_ioc: str, use_mock=True) -> dict:
    """
    Hàm bọc API Client để trinh sát IP/Domain.
    - use_mock=True: Trả về kết quả ngay lập tức (Dành cho Demo/Bảo vệ đồ án).
    - use_mock=False: Gọi SpiderFoot thật, đợi tối đa 60s rồi lấy kết quả.
    """
    logging.info(f"[~] OSINT Module đang trinh sát mục tiêu: {target_ioc}...")
    
    if use_mock:
        # Trả về dữ liệu giả lập ngay lập tức để không làm nghẽn Pipeline AI
        time.sleep(1) # Giả lập độ trễ mạng
        return {
            "target": target_ioc,
            "risk_score": "High",
            "associated_threats": ["Ransomware C2", "CobaltStrike Beacon"],
            "malicious_votes_virustotal": 18,
            "shodan_ports": [80, 443, 8080],
            "note": "OSINT Data provided by SpiderFoot Pipeline"
        }
    
    # --- LUỒNG CHẠY THẬT (PRODUCTION) ---
    client = SpiderFootClient()
    scan_name = f"AutoCTI_{target_ioc}_{int(time.time())}"
    
    scan_id = client.start_scan(scan_name, target_ioc)
    if not scan_id:
        return {"error": "Không thể khởi động SpiderFoot scan."}
    
    # Đợi tối đa 60 giây (Chỉ quét các module nhanh)
    max_wait_time = 60
    waited = 0
    while waited < max_wait_time:
        status = client.get_scan_status(scan_id)
        if status in ["FINISHED", "ABORTED"]:
            break
        time.sleep(10)
        waited += 10
        logging.info(f"   ... Đang chờ OSINT Scan ({waited}s / {max_wait_time}s)")
        
    # Lấy kết quả thô
    raw_results = client.get_scan_results(scan_id)
    
    # Trích xuất gọn gàng lại cho AI dễ đọc (Tránh JSON quá to làm AI bị "ảo giác")
    summary = {
        "target": target_ioc,
        "total_data_points_found": len(raw_results),
        "status": "partial_scan" if waited >= max_wait_time else "completed"
    }
    return summary